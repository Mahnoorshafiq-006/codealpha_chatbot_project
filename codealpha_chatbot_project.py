"""tf-idf vectorization and cosine similarity"""

faq_items = [item for items in faq_database.values() for item in items]

# Use question_clean directly — analyzer=lambda x: x tells the vectorizer
# "don't tokenize this yourself, treat each list as already-tokenized"
vectorizer = TfidfVectorizer(analyzer=lambda tokens: tokens)
tfidf_matrix = vectorizer.fit_transform([item['question_clean'] for item in faq_items])

def get_best_answer(user_query, top_n=1):
    # preprocess the user query the exact same way the FAQ questions were processed
    query_tokens = [
        w for w in nltk.word_tokenize(user_query.lower())
        if w not in stop_words
    ]
    query_clean = [
        lemmatizer.lemmatize(w) for w in query_tokens
        if w not in string.punctuation and w.isalpha()
    ]

    # if nothing meaningful survives cleaning, don't even bother vectorizing
    if not query_clean:
        return [{"question": None, "answer": "Sorry, I didn't understand that. Could you rephrase your question?", "score": 0.0}]

    # transform (not fit_transform) — reuse the vocabulary learned from the FAQ set
    query_vector = vectorizer.transform([query_clean])

    # compare the query vector against every FAQ question vector
    similarities = cosine_similarity(query_vector, tfidf_matrix).flatten()

    # get indices of the top_n most similar questions, highest first
    top_indices = similarities.argsort()[::-1][:top_n]

    # Define a minimum similarity score to consider an answer valid
    min_score = 0.3 # You can adjust this threshold as needed

    # Get the score of the most similar question
    best_score = similarities[top_indices[0]]
# don't guass, print sorry to user
    if best_score < min_score:
        return [
            {
                "question": None,
                "answer": "Sorry, I don't have an answer for that. Could you try rephrasing, or ask about orders, payments, returns, or shipping?",
                "score": round(float(best_score), 3)
            }
        ]

    results = []
    for idx in top_indices:
        results.append({
            "question": faq_items[idx]['question_raw'],
            "answer": faq_items[idx]['answer_raw'],
            "score": round(float(similarities[idx]), 3)
        })
    return results
