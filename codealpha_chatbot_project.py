"""Data preprocessing using nltk"""

lemmatizer = WordNetLemmatizer()

stop_words = set(stopwords.words('english'))

for category, items in faq_database.items():
    for item in items:
        # keep raw text untouched — never overwritten
        item['question_raw'] = item['question']
        item['answer_raw'] = item['answer']

        # build new processed fields, don't touch the originals
        item['question_tokens'] = [
            w for w in nltk.word_tokenize(item['question_raw'].lower())
            if w not in stop_words
        ]
        item['answer_tokens'] = [
            w for w in nltk.word_tokenize(item['answer_raw'].lower())
            if w not in stop_words
        ]

        item['question_clean'] = [
            lemmatizer.lemmatize(w) for w in item['question_tokens']
            if w not in string.punctuation and w.isalpha()
        ]
        item['answer_clean'] = [
            lemmatizer.lemmatize(w) for w in item['answer_tokens']
            if w not in string.punctuation and w.isalpha()
        ]
  # NEW: fold alt phrasings into question_clean so the vectorizer
        # learns those extra words too
        alt_phrasings = item.get('alt_phrasings', [])
        for phrase in alt_phrasings:
            phrase_tokens = [
                w for w in nltk.word_tokenize(phrase.lower())
                if w not in stop_words
            ]
            phrase_clean = [
                lemmatizer.lemmatize(w) for w in phrase_tokens
                if w not in string.punctuation and w.isalpha()
            ]
            item['question_clean'].extend(phrase_clean)

